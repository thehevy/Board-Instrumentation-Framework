        """Run interactive wizard"""
        print("\n" + "="*70)
        print("  BIFF Collector Builder - Interactive Wizard")
        print("="*70)
        
        # Step 1: Metric name
        print("\n📊 Step 1: What metric do you want to collect?")
        metric_name = self._prompt("Metric name (e.g., GPU Temperature, API Response Time)")
        self.responses['metric_name'] = metric_name
        
        # Step 2: Data source type
        print("\n📁 Step 2: What type of data source?")
        source_options = list(self.DATA_SOURCE_TYPES.keys())
        source_descriptions = [f"{k}: {v}" for k, v in self.DATA_SOURCE_TYPES.items()]
        source_choice = self._prompt("Data source type", source_descriptions)
        source_type = source_choice.split(':')[0]
        self.responses['source_type'] = source_type
        
        # Step 3: Template selection
        if source_type == 'system':
            template_key = 'psutil'
