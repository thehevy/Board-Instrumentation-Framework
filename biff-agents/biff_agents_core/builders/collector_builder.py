class DynamicCollectorTemplate(CollectorTemplate):
    """Template for DynamicCollector file watcher (XML-only, no Python code)"""
    
    def __init__(self):
        super().__init__(
            "DynamicCollector File Watcher",
            "Watch a file for metrics in 'name=value' format (zero instrumentation)"
        )
    
    def get_required_params(self) -> List[str]:
        return ['metric_prefix', 'file_path', 'frequency', 'precision']
    
    def generate(self, params: Dict) -> str:
        """Generate DynamicCollector XML configuration"""
        metric_prefix = params['metric_prefix']
        file_path = params['file_path']
        frequency = params.get('frequency', 1000)
        precision = params.get('precision', 0)
        send_on_change = params.get('send_on_change', False)
        
        # Build XML line by line
        lines = []
        if send_on_change:
            lines.append(f'<DynamicCollector Prefix="{metric_prefix}." OnlySendOnChange="True" Frequency="{frequency}">')
        else:
            lines.append(f'<DynamicCollector Prefix="{metric_prefix}." Frequency="{frequency}">')
        
        lines.append(f'    <File>{file_path}</File>')
        lines.append(f'    <Precision>{precision}</Precision>')
        lines.append('</DynamicCollector>')
        
        return '\n'.join(lines)
    
    def get_usage_notes(self) -> str:
        """Return usage notes for this collector type"""
        return """
DynamicCollector File Watcher - Usage Notes:
--------------------------------------------
• File format: Each line should be 'metric.name=value'
• Example file content:
    cpu.usage=45.2
    memory.free=8192
    disk.io=1234
    
• Prefix is automatically added to all metric names
• All metrics in file are auto-discovered
• No Python code required - pure XML configuration
• Perfect for test harnesses, CI/CD outputs, application logs

Production Example (Intel Vision Demo):
  15 instances collecting test results from files
  Zero code maintenance, pure data-driven monitoring
"""


class CollectorWizard:
    """Interactive wizard for creating new collectors"""
    
    TEMPLATES = {
        'shell': ShellCommandTemplate(),
        'file': FileParserTemplate(),
        'psutil': PsutilTemplate(),
        'api': APIPollerTemplate(),
        'plugin': PluginTemplate(),
        'plugin_framework': PluginFrameworkTemplate(),
        'dynamic_file': DynamicCollectorTemplate()
    }
    
    DATA_SOURCE_TYPES = {
        'system': 'System metrics (CPU, memory, disk, network)',
        'command': 'Wrap existing command-line tool',
        'file': 'Parse file or log file',
        'dynamic_file': 'File watcher (auto-discover metrics)',
        'api': 'Poll REST API',
        'plugin_framework': 'Plugin with framework interface (dynamic discovery)',
        'custom': 'Custom Python code'
    }
    
    FREQUENCIES = {
        '500ms': 500,
        '1s': 1000,
        '5s': 5000,
        '10s': 10000,
        '30s': 30000,
        '60s': 60000
    }
    
    def __init__(self):
        self.responses = {}
    
    def _prompt(self, question: str, options: Optional[List[str]] = None, default: Optional[str] = None) -> str:
        """Prompt user for input (strips BOM for Windows PowerShell compatibility)"""
        if options:
            print(f"\n{question}")
            for i, option in enumerate(options, 1):
                print(f"  {i}. {option}")
            
            while True:
                choice = input(f"Choose (1-{len(options)}){f' [{default}]' if default else ''}: ").strip()
                
                # Strip BOM if present (Windows PowerShell compatibility)
                if choice.startswith('\ufeff'):
                    choice = choice[1:]
                elif choice.startswith('ï»¿'):
                    choice = choice[3:]
                
                if not choice and default:
                    return default
                try:
                    idx = int(choice) - 1
                    if 0 <= idx < len(options):
                        return options[idx]
                except ValueError:
                    pass
                print("Invalid choice. Try again.")
        else:
            prompt_text = f"{question}"
            if default:
                prompt_text += f" [{default}]"
            prompt_text += ": "
            
            response = input(prompt_text).strip()
            
            # Strip BOM if present (Windows PowerShell/echo adds UTF-8 BOM)
            if response.startswith('\ufeff'):
                response = response[1:]
            elif response.startswith('ï»¿'):
                response = response[3:]
            
            return response if response else (default or "")
    
    def _validate_metric_id(self, metric_id: str) -> Tuple[bool, str]:
        """Validate metric ID format"""
        if not metric_id:
            return False, "Metric ID cannot be empty"
        
        # Check for valid characters (alphanumeric, dots, underscores, hyphens)
        import re
        if not re.match(r'^[a-zA-Z0-9._-]+$', metric_id):
            return False, "Metric ID can only contain letters, numbers, dots, underscores, and hyphens"
        
        # Check if it starts with a letter
        if not metric_id[0].isalpha():
            return False, "Metric ID must start with a letter"
        
        return True, ""
    
