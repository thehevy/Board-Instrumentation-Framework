"""
Minion Collector Builder

Interactive wizard for creating new Minion collectors with templates and configuration updates.
"""

import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple


class CollectorTemplate:
    """Base class for collector templates"""
    
    def __init__(self, name: str, description: str):
        self.name = name
        self.description = description
    
    def generate(self, params: Dict) -> str:
        """Generate collector code from parameters"""
        raise NotImplementedError("Subclasses must implement generate()")
    
    def get_required_params(self) -> List[str]:
        """Get list of required parameters for this template"""
        raise NotImplementedError("Subclasses must implement get_required_params()")


class ShellCommandTemplate(CollectorTemplate):
    """Template for wrapping shell commands"""
    
    def __init__(self):
        super().__init__(
            "Shell Command",
            "Wrap an existing command-line tool (e.g., nvidia-smi, sensors, iperf)"
        )
    
